const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

function GoWild({ run, reduced }: { run: number; reduced: boolean }) {
  const root = useRef<HTMLSpanElement>(null);
  const api = useRef<{ play: () => void; finish: () => void } | null>(null);

  useEffect(() => {
    const l2 = root.current;
    if (!l2) return;
    const cast = l2.querySelector(".gw-cast") as HTMLElement;
    const mw = l2.querySelector(".mw") as HTMLElement;
    const flipper = l2.querySelector(".flipper") as HTMLElement;
    cast.innerHTML = "";
    const mk = (html: string, cls: string) => {
      const el = document.createElement("span");
      el.className = cls;
      el.innerHTML = html;
      cast.appendChild(el);
      return el;
    };
    type T = { el: HTMLElement; svg: SVGElement; x: number; y: number; r: number };
    const actor = (svg: string, cls: string): T => {
      const el = mk(`<span class="face-dir">${svg}</span>`, cls);
      return { el, svg: el.querySelector("svg") as SVGElement, x: 0, y: 0, r: 0 };
    };
    const ground = mk("", "ground");
    const A = actor(TIGER_A, "actor a");
    const B = actor(TIGER_B, "actor b");

    let G: any;
    let token = 0;
    const geo = () => {
      const cs = getComputedStyle(l2);
      const fs = parseFloat(cs.fontSize);
      const box = l2.getBoundingClientRect();
      const base = (l2.querySelector(".bl") as HTMLElement).getBoundingClientRect().top - box.top;
      const c = document.createElement("canvas").getContext("2d")!;
      c.font = `${cs.fontWeight} ${fs}px ${cs.fontFamily}`;
      const wid = (ch: string) => c.measureText(ch).width;
      const m = mw.getBoundingClientRect();
      const W = fs * 0.6, H = W * 1.4, u = W / 40;
      return { fs, base, mC: m.left - box.left + wid("m") / 2, mW: wid("m"), wW: wid("w"), W, H, u, feet: (H * 47.3) / 56 };
    };
    const tf = (x: number, y: number, r = 0) => `translate(${x - G.W / 2}px, ${y - G.feet}px) rotate(${r}deg)`;
    const put = (t: T, x: number, y: number, r = 0) => {
      t.el.getAnimations().forEach((a) => a.cancel());
      Object.assign(t, { x, y, r });
      t.el.style.width = G.W + "px";
      t.el.style.transformOrigin = `${G.W / 2}px ${G.feet}px`;
      t.el.style.transform = tf(x, y, r);
      t.el.style.opacity = "1";
    };
    const pose = (t: T, o: Record<string, string | null>) => {
      for (const k in o) o[k] == null ? t.svg.removeAttribute("data-" + k) : t.svg.setAttribute("data-" + k, o[k] as string);
    };
    const go = async (t: T, x: number, y: number, ms: number, opt: { r?: number; ease?: string } = {}) => {
      const r = opt.r ?? t.r;
      const a = t.el.animate([{ transform: tf(t.x, t.y, t.r) }, { transform: tf(x, y, r) }], { duration: ms, easing: opt.ease ?? "ease-in-out", fill: "forwards" });
      Object.assign(t, { x, y, r });
      await a.finished.catch(() => {});
    };
    const jump = async (t: T, x: number, y: number, ms: number, h: number) => {
      const k = [], x0 = t.x, y0 = t.y;
      for (let i = 0; i <= 18; i++) {
        const s = i / 18;
        k.push({ transform: tf(x0 + (x - x0) * s, y0 + (y - y0) * s - 4 * h * s * (1 - s), t.r) });
      }
      const a = t.el.animate(k, { duration: ms, easing: "linear", fill: "forwards" });
      Object.assign(t, { x, y });
      await a.finished.catch(() => {});
    };
    const layGround = (gy: number, fade: boolean) => {
      const L = Math.max(G.W * 0.6, G.mC - G.fs * 1.3), R = G.mC + G.fs * 1.3;
      ground.style.width = R - L + G.W + "px";
      ground.style.transform = `translate(${L - G.W / 2}px, ${gy - 1}px)`;
      ground.getAnimations().forEach((a) => a.cancel());
      if (fade) ground.animate([{ opacity: 0 }, { opacity: 0.18 }], { duration: 400, fill: "forwards" });
      else ground.style.opacity = "0.18";
      return [L, R];
    };
    const resetLetter = () => {
      flipper.getAnimations().forEach((a) => a.cancel());
      mw.getAnimations().forEach((a) => a.cancel());
      flipper.style.transform = "";
      mw.style.width = "";
    };
    const hoistM = (lift: number) => {
      const T = 1160; // 300 up · 560 flip · 300 down, in step with the tigers
      flipper.animate(
        [
          { transform: "translateY(0) rotateX(0deg)", easing: "ease-out" },
          { transform: `translateY(${-lift}px) rotateX(0deg)`, offset: 300 / T, easing: "cubic-bezier(.4,0,.3,1)" },
          { transform: `translateY(${-lift}px) rotateX(190deg)`, offset: 760 / T, easing: "ease-in-out" },
          { transform: `translateY(${-lift}px) rotateX(180deg)`, offset: 860 / T, easing: "ease-in-out" },
          { transform: "translateY(0) rotateX(180deg)" },
        ],
        { duration: T, fill: "forwards" },
      );
      mw.animate([{ width: G.mW + "px" }, { width: G.wW + "px" }], { duration: 240, delay: 430, easing: "ease-out", fill: "forwards" });
    };

    // the finished frame: "wild", the two of them standing under it
    const finish = () => {
      token++;
      resetLetter();
      G = geo();
      const gy = G.base + 64.6 * G.u;
      layGround(gy, false);
      flipper.style.transform = "rotateX(180deg)";
      mw.style.width = G.wW + "px";
      put(A, G.mC - 12 * G.u, gy);
      put(B, G.mC + 12 * G.u, gy);
      pose(A, { arms: "down", legs: "stand", look: null });
      pose(B, { arms: "down", legs: "stand", look: null });
    };

    const play = async () => {
      const id = ++token;
      const gone = () => id !== token;
      resetLetter();
      G = geo();
      const g = G;
      mw.style.width = g.mW + "px";
      const reach = 64.6 * g.u, gy = g.base + reach, sh = 27.3 * g.u;
      const [L, R] = layGround(gy, true);
      put(A, L, gy);
      put(B, R, gy);
      pose(A, { arms: "down", legs: "stand", look: null });
      pose(B, { arms: "down", legs: "stand", look: null });
      await sleep(450); if (gone()) return;
      // walk in under the m
      pose(A, { legs: "run" }); pose(B, { legs: "run" });
      go(A, g.mC - 15 * g.u, gy, 900);
      await go(B, g.mC, gy, 900); if (gone()) return;
      pose(A, { legs: "stand", look: "up" }); pose(B, { legs: "stand", look: "up" });
      await sleep(450); if (gone()) return;
      // gold crouches to give a boost
      pose(B, { legs: "crouch", arms: "lift", look: null }); pose(A, { look: null });
      await sleep(260); if (gone()) return;
      pose(A, { legs: "crouch" });
      await sleep(150); if (gone()) return;
      pose(A, { legs: "tuck", arms: "up" });
      await jump(A, g.mC, gy - sh - 3.5 * g.u, 440, g.u * 12); if (gone()) return;
      pose(A, { legs: "stand" }); pose(B, { legs: "stand" });
      await go(A, g.mC, gy - sh, 160, { ease: "ease-out" }); if (gone()) return;
      // reach, wobble on tiptoe
      pose(A, { look: "up" });
      await go(A, g.mC, gy - sh - 1.4 * g.u, 160, { r: -4 });
      await go(A, g.mC, gy - sh, 160, { r: 3 });
      await go(A, g.mC, gy - sh - 1.2 * g.u, 160, { r: -2 }); if (gone()) return;
      // HOIST: gold pushes orange up, orange lifts the m with it, flips it
      const lift = 9.8 * g.u;
      pose(B, { arms: "up", look: "up" });
      hoistM(lift);
      await go(A, g.mC, gy - sh - lift, 300, { r: 0, ease: "ease-out" }); if (gone()) return;
      await sleep(560); if (gone()) return;
      // ...and lowers it, as a w, exactly into the m's spot
      pose(B, { arms: "lift" });
      await go(A, g.mC, gy - sh, 300); if (gone()) return;
      await sleep(250); if (gone()) return;
      // orange hops down, they step back and admire it
      pose(A, { legs: "tuck", arms: "down", look: null }); pose(B, { look: null });
      await jump(A, g.mC - 12 * g.u, gy, 420, g.u * 6); if (gone()) return;
      pose(A, { legs: "crouch" }); pose(B, { legs: "run" });
      await go(B, g.mC + 12 * g.u, gy, 300); if (gone()) return;
      pose(A, { legs: "stand", look: "up" }); pose(B, { legs: "stand", look: "up" });
      await sleep(500); if (gone()) return;
      pose(A, { arms: "cheer", look: null }); pose(B, { arms: "cheer", look: null });
      await sleep(700); if (gone()) return;
      pose(A, { arms: "down" }); pose(B, { arms: "down" });
    };

    api.current = { play, finish };
    let rt = 0;
    const onResize = () => { clearTimeout(rt); rt = window.setTimeout(finish, 150); };
    window.addEventListener("resize", onResize);
    return () => { token++; window.removeEventListener("resize", onResize); api.current = null; };
  }, []);

  useEffect(() => {
    const go = () => {
      if (!api.current) return;
      if (reduced) api.current.finish();
      else if (run > 0) api.current.play();
    };
    const fonts = (document as any).fonts;
    if (fonts?.ready) fonts.ready.then(go, go);
    else go();
  }, [run, reduced]);

  return (
    <span ref={root} className="gw">
      G<span className="o">o</span>{" "}
      <span className="mw">
        <span className="ghost">m</span>
        <span className="flipper">
          <span className="face m">m</span>
          <span className="face w">w</span>
        </span>
      </span>
      ild.
      <span className="bl" />
      <span className="gw-cast" />
    </span>
  );
}

export default memo(GoWild);
