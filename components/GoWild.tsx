/* "Go mild." becomes "Go wild." — the two tiger friends walk in under the
   m, gold boosts orange onto its shoulders, they hoist the letter up, flip
   it over in the air and set it back down as a w, exactly in its place.

   The words are ordinary server-rendered text. The tigers live in their own
   empty layer (.gw-cast) that React never renders into, so re-renders can't
   disturb the running timeline. Positions are measured from the real glyphs
   (baseline, m centre, m/w widths), so it lines up at any size.
   Replays each time `run` changes; reduced motion shows the finished frame.
   Generated by scratchpad/home-redesign/gowild.py. */

